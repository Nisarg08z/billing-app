// Downloads the app fonts (Bodoni Moda + Figtree, SIL Open Font License) from Google Fonts into
// www/fonts and writes www/fonts/fonts.css, so the app has its fonts with no internet.
// Only the latin and latin-ext subsets are kept (latin-ext carries the ₹ sign).
// Usage: node scripts/get-fonts.js
const fs = require('fs');
const path = require('path');

const CSS_URL = 'https://fonts.googleapis.com/css2?family=Bodoni+Moda:opsz,wght@6..96,500..700&family=Figtree:wght@400..800&display=swap';
const KEEP = ['latin', 'latin-ext'];
const out = path.join(__dirname, '..', 'www', 'fonts');

(async () => {
  // A modern browser user agent makes Google serve woff2 split by subset
  const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36' } })).text();
  const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]+\})/g)].filter(m => KEEP.includes(m[1]));
  if (!blocks.length) throw new Error('No font blocks found in Google Fonts CSS');
  fs.mkdirSync(out, { recursive: true });
  let local = '/* Generated by scripts/get-fonts.js. Fonts: Bodoni Moda, Figtree (SIL Open Font License 1.1) */\n';
  for (const [, subset, block] of blocks) {
    const family = block.match(/font-family:\s*'([^']+)'/)[1];
    const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
    const file = `${family.replace(/\s+/g, '')}-${subset}.woff2`;
    const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
    fs.writeFileSync(path.join(out, file), buf);
    console.log(`${file}  ${(buf.length / 1024).toFixed(0)} KB`);
    local += `/* ${subset} */\n` + block.replace(url, file) + '\n';
  }
  fs.writeFileSync(path.join(out, 'fonts.css'), local);
  console.log('fonts.css written');
})().catch(e => { console.error(e.message); process.exit(1); });
